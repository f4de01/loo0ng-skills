"""种子「在办中」：一个已经办了几步的案件工作区。

用法：python 回放.py <工作区>    （由 scripts/skill-eval.py 调，也可手跑）
按出厂预设图「破产」起手（走真的起手 CLI：目录形状、图与两份视图、19 件官方模板原件、指针块都由它落），
再逐条调归档与图引擎摆状态：材料一件经归档 CLI 搬进 材料/ 并进归档索引；待归档里还留一份指南没归；
节点「管理人承诺书及团队人员」已确认（文书里没有黄）、「管理人印章备案报告」已生成未确认（文书里
还有一处黄）；材料/律师说过的.md 里四行律师在对话里说过的话。
待归档/债务人移交物品清单.txt 由跑器按种子接口原样拷进工作区，那份指南从种子「空目录」借。
工作区里没有任何案件内容：文书与审查报告都是合成的几行字，当事人与法院一律写甲乙丙。
"""
import pathlib
import shutil
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "共用"))
import 基线  # noqa: E402
import 回放助手 as 助手  # noqa: E402

SEED_DIR = pathlib.Path(__file__).resolve().parent
借来的指南 = SEED_DIR.parent / "空目录" / "甲法院破产案件管理人工作提示.md"

已确认 = "管理人承诺书及团队人员"
已生成 = "管理人印章备案报告"
材料 = "债务人移交物品清单.txt"
律师说过的 = """2026-09-12 受理裁定是甲年乙月丙日作的，申请人甲公司，债务人乙公司，简称乙公司。
2026-09-12 管理人是丙律师事务所，负责人丁某。
2026-09-13 指定管理人决定书是甲年乙月丙日收到的。
2026-09-13 先把印章备案办完再动账户。
"""


def main(workspace: str) -> int:
    ws = pathlib.Path(workspace)
    助手.起手(ws, 助手.破产)
    助手.归档(ws, [{"路径": 材料, "去向": "材料", "说明": "债务人移交物品清单，接管当天双方签字的合成清单"}])
    shutil.copy2(str(借来的指南), str(ws / "待归档" / 借来的指南.name))
    (ws / "材料" / "律师说过的.md").write_text(律师说过的, encoding="utf-8")
    助手.办完(ws, 已确认, "承诺书这份就这样，可以了")
    助手.出一版(ws, 已生成, 高亮=True)
    基线.写基线(ws)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
